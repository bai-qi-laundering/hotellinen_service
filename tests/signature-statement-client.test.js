import {test} from 'node:test';
import assert from 'node:assert/strict';
import {candidateClosingDates,createSignatureStatementClient} from '../signature-statement-client.js';
import {caseDocumentId} from '../statement-case.js';
function setup({date='2026-11-25',signed=true,failFetch=false,failTransaction=false}={}) {
 const data=new Map([
  ['inventory_config/finance_settlement_groups',{groups:{富野:'25th'}}],
  ['inventory_config/master_template',{items:[{hotel:'富野 房務',item:'床單'}]}],
 ]);
 const records=[{id:'closing',data:{date,hotelKeyword:'富野',deptName:'房務',clientSig:signed?'signature-url':'',items:[{itemName:'床單',actualQty:2,price:10}]}},
 {id:'prior',data:{date:'2026-10-26',hotelKeyword:'富野',deptName:'房務',items:[{itemName:'床單',actualQty:3,price:10}]}}];
 let serial=Promise.resolve(),fetches=0,transactions=0;
 const snap=(value)=>({exists:()=>value!==undefined,data:()=>value});
 const fns={doc:(_db,col,id)=>({key:col+'/'+id}),collection:(_db,col)=>({col}),where:(field,op,value)=>({field,op,value}),
  query:(col,...filters)=>({...col,filters}),
  getDoc:async ref=>snap(data.get(ref.key)),
  getDocs:async q=>{
   const match=records.filter(r=>q.filters.every(f=>{
    const value=r.data[f.field];
    if(typeof value!==typeof f.value || (value instanceof Date)!==(f.value instanceof Date))return false;
    return f.op==='=='?value===f.value:f.op==='>='?value>=f.value:value<=f.value;
   }));
   return {forEach:cb=>match.forEach(r=>cb({id:r.id,data:()=>r.data}))};
  },
  runTransaction:(_db,work)=>{
   const run=serial.then(async()=>{
    transactions++;if(failTransaction)throw Error('雲端寫入失敗');
    const writes=[];
    const result=await work({get:async ref=>snap(data.get(ref.key)),set:(ref,value)=>writes.push([ref.key,value])});
    writes.forEach(([k,v])=>data.set(k,v));return result;
   });serial=run.catch(()=>{});return run;
  }
 };
 const stored=new Map(),statuses=[];
 const storage={getItem:k=>stored.get(k)||null,setItem:(k,v)=>stored.set(k,v)};
 const fetchFn=async()=>{fetches++;if(failFetch)throw Error('網路中斷');return {ok:true,json:async()=>({success:true,prices:[['表頭']],clients:[['富野','富野股份有限公司','12345678','聯絡人']]})}};
 const client=(clockDate)=>createSignatureStatementClient({},fns,storage,{clock:()=>new Date(clockDate+'T04:00:00Z'),fetchFn,onStatus:(message,kind)=>statuses.push({message,kind})});
 return {data,records,stored,statuses,client,setFetchFailure:v=>{failFetch=v},setTransactionFailure:v=>{failTransaction=v},counts:()=>({fetches,transactions})};
}
test('closing date candidates do not automatically backfill before activation or future periods',()=>{
 assert.equal(candidateClosingDates('2026-10-30','2026-10-25').includes('2026-10-25'),false);
 assert.equal(candidateClosingDates('2026-11-24','2026-11-25').includes('2026-11-25'),false);
 assert.equal(candidateClosingDates('2026-11-26','2026-11-26').includes('2026-11-25'),true);
});
test('first closing signature publishes exact full-period invoice and reopening leaves changes alone',async()=>{
 const s=setup(),client=s.client('2026-11-25');
 assert.deepEqual(await client.run('富野','2026-11-25'),{created:1,existing:0});
 const id=await caseDocumentId('富野','2026-10-26','2026-11-25'),key='statement_cases/'+id;
 const doc=s.data.get(key);
 assert.equal(doc.versions[0].snapshot.totals.grandTotal,50);
 assert.equal(doc.versions[0].snapshot.totals.tax,3);
 assert.equal(doc.autoGenerated,true);
 doc.latestVersion=4;s.records[0].data.items[0].actualQty=99;
 assert.deepEqual(await s.client('2026-11-26').run('富野','2026-11-26'),{created:0,existing:1});
 assert.equal(s.data.get(key).latestVersion,4);assert.equal(s.counts().fetches,1);
});
test('no signed closing receipt does not generate a statement or fetch prices',async()=>{
 const s=setup({signed:false});
 assert.deepEqual(await s.client('2026-11-25').run('富野','2026-11-25'),{created:0,existing:0});
 assert.equal(s.counts().fetches,0);
});
test('a failed master-data request is retried on reopen and produces one invoice',async()=>{
 const s=setup({failFetch:true});
 await assert.rejects(s.client('2026-11-25').run('富野','2026-11-25'),/網路中斷/);
 assert.equal([...s.data.keys()].filter(k=>k.startsWith('statement_cases/')).length,0);
 assert.ok([...s.stored.values()].some(v=>v.includes('2026-11-25')));
 s.setFetchFailure(false);
 assert.equal((await s.client('2026-11-26').run('富野','2026-11-26')).created,1);
});
test('two devices race; a single atomic case survives, without a separate collection permission',async()=>{
 const s=setup();
 const results=await Promise.all([s.client('2026-11-25').run('富野','2026-11-25'),s.client('2026-11-25').run('富野','2026-11-25')]);
 assert.equal(results.reduce((n,r)=>n+r.created,0),1);
 assert.equal([...s.data.keys()].filter(k=>k.startsWith('statement_cases/')).length,1);
});
test('an existing manual invoice is not replaced',async()=>{
 const s=setup(),id=await caseDocumentId('富野','2026-10-26','2026-11-25');
 s.data.set('statement_cases/'+id,{latestVersion:8,manual:true});
 await s.client('2026-11-25').run('富野','2026-11-25');
 assert.deepEqual(s.data.get('statement_cases/'+id),{latestVersion:8,manual:true});
 assert.equal(s.counts().fetches,0);
});
test('transaction failure preserves retry intent and does not report invoice success',async()=>{
 const s=setup({failTransaction:true});
 await assert.rejects(s.client('2026-11-25').run('富野','2026-11-25'),/雲端寫入失敗/);
 assert.equal(s.statuses.some(x=>x.kind==='success'),false);
 s.setTransactionFailure(false);
 assert.equal((await s.client('2026-11-26').run('富野','2026-11-26')).created,1);
});
