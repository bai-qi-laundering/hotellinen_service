// Browser-side automatic statement creation. Signature saving remains independent.
import { legacyDatePrefixes } from './logistics-items.js';
import { caseDocumentId, publishSnapshot } from './statement-case.js';
import { closingPeriod, customerOf, rowsForPeriod, recordDate, taipeiDate, createInvoiceEngine } from './firebase-signature/functions/lib/auto-close.js';

export const ACTIVE_FROM = '2026-10-30';
const GAS_URL = 'https://script.google.com/macros/s/AKfycbxkUiqCGa85QiI8P91p4DEnd6exOuQ4VnBt4r-hrrQHImE-3Bg0KO3yVR3_EbG5yHovtA/exec';
const PENDING_KEY = 'baiqi_signature_statement_pending_v1';
const hasSignature = d => !!(String(d.clientSig || '').trim() || String(d.driverSig || '').trim());
const signed = d => !d.manualDeletedReceipt && hasSignature(d);
export function candidateClosingDates(today, selectedDate, activeFrom=ACTIVE_FROM) {
 const [y,m]=today.split('-').map(Number), dates=new Set();
 for(const offset of [-1,0]) {
  const first=new Date(Date.UTC(y,m-1+offset,1));
  const year=first.getUTCFullYear(),month=first.getUTCMonth();
  dates.add(new Date(Date.UTC(year,month,25)).toISOString().slice(0,10));
  dates.add(new Date(Date.UTC(year,month+1,0)).toISOString().slice(0,10));
 }
 if(selectedDate) dates.add(selectedDate);
 return [...dates].filter(d=>/^\d{4}-\d{2}-\d{2}$/.test(d)&&d>=activeFrom&&d<=today).sort().reverse();
}
export async function publishAutomaticOnce(db,fns,snapshot,source={}) {
 const id=await caseDocumentId(snapshot.customerKey,snapshot.startDate,snapshot.endDate);
 const ref=fns.doc(db,'statement_cases',id);
 return fns.runTransaction(db,async tx=>{
  const existing=await tx.get(ref);
  if(existing.exists()) return {action:'existing',id};
  const now=new Date().toISOString();
  const result=await publishSnapshot(null,snapshot,now);
  tx.set(ref,JSON.parse(JSON.stringify({...result.doc,id,cloudPending:false,autoGenerated:true,
   autoGeneration:{completedAt:now,source:'signature-page',...source}})));
  return {action:'created',id};
 });
}
export function createSignatureStatementClient(db,fns,storage,{
 fetchFn=globalThis.fetch,clock=()=>new Date(),onStatus=()=>{},activeFrom=ACTIVE_FROM,masterUrl=GAS_URL
}={}) {
 let chain=Promise.resolve();
 function pending() {try{return JSON.parse(storage.getItem(PENDING_KEY)||'{}')}catch{return {}}}
 function remember(hotel,date,remove=false) {try{const box=pending(),key=hotel+'|'+date;if(remove)delete box[key];else box[key]={hotel,date};storage.setItem(PENDING_KEY,JSON.stringify(box))}catch{}}
 async function read(promise) {
  let timer;try{return await Promise.race([promise,new Promise((_,reject)=>{timer=setTimeout(()=>reject(new Error('雲端讀取逾時，請重新開啟簽單補產')),20000)})])}finally{clearTimeout(timer)}
 }
 async function config(name) {const snap=await read(fns.getDoc(fns.doc(db,'inventory_config',name)));return snap.exists()?snap.data():{}}
 async function readPeriod(start,end) {
  const collection=fns.collection(db,'logistics_records');
  const variants=start===end ? [...new Set([start,start.replace(/-0/g,'-'),start.slice(0,7)+'-'+Number(start.slice(8)),start.slice(0,4)+'-'+Number(start.slice(5,7))+'-'+start.slice(8)])] : null;
  const queries=variants ? variants.map(date=>fns.query(collection,fns.where('date','==',date))) : legacyDatePrefixes(start,end).map(prefix=>fns.query(collection,fns.where('date','>=',prefix),fns.where('date','<=',prefix+'\uf8ff')));
  queries.push(fns.query(collection,fns.where('date','>=',new Date(start+'T00:00:00+08:00')),fns.where('date','<=',new Date(end+'T23:59:59.999+08:00'))));
  const all=new Map();
  for(const snapshot of await Promise.all(queries.map(q=>read(fns.getDocs(q)))))snapshot.forEach(d=>{
   const data=d.data(),date=recordDate(data.date);if(date>=start&&date<=end)all.set(d.id,{id:d.id,data});
  });
  return [...all.values()];
 }
 async function loadMaster() {
  const response=await fetchFn(masterUrl+'?action=getFinanceMasterData',{signal:AbortSignal.timeout(15000)});
  if(!response.ok)throw new Error('財務資料讀取失敗 HTTP '+response.status);
  const data=await response.json();
  if(!data.success||!Array.isArray(data.prices)||!Array.isArray(data.clients))throw new Error('財務價目或客戶資料不完整');
  return data;
 }
 async function execute(hotel,selectedDate) {
  if(!hotel)return {created:0,existing:0};
  const today=taipeiDate(clock());
  const groups=(await config('finance_settlement_groups')).groups||{};
  const dates=candidateClosingDates(today,selectedDate,activeFrom);
  for(const entry of Object.values(pending()))if(entry.hotel===hotel&&entry.date>=activeFrom&&entry.date<=today&&!dates.includes(entry.date))dates.push(entry.date);
  // Only the latest due period, plus the specifically selected/pending closing dates.
  const due=date=>closingPeriod(hotel,date,groups)||Object.keys(groups).some(k=>k.startsWith(hotel+' ')&&closingPeriod(k,date,groups));
  const latest=dates.filter(due).sort().at(-1);
  const chosen=new Set([latest,selectedDate,...Object.values(pending()).filter(x=>x.hotel===hotel).map(x=>x.date)].filter(d=>dates.includes(d)));
  let created=0,existing=0,contextPromise;
  const context=()=>contextPromise ||= Promise.all([loadMaster(),config('finance_annual_pricing'),config('finance_effective_prices'),config('custom_prices'),config('master_template')]);
  for(const date of chosen) {
   // Explicit customer-level group overrides (e.g. 鼎王 departments) are checked below.
   if(!closingPeriod(hotel,date,groups)&&!Object.keys(groups).some(k=>k.startsWith(hotel+' ')&&closingPeriod(k,date,groups)))continue;
   const closingDocs=(await readPeriod(date,date)).filter(x=>String(x.data.hotelKeyword||'').trim()===hotel&&signed(x.data));
   const customers=[...new Set(closingDocs.map(x=>customerOf(x.data)))];
   for(const customer of customers) {
    const period=closingPeriod(Object.hasOwn(groups,customer)?customer:hotel,date,groups);
    if(!period)continue;
    const id=await caseDocumentId(customer,period.startDate,period.endDate);
    if((await read(fns.getDoc(fns.doc(db,'statement_cases',id)))).exists()){existing++;continue;}
    remember(hotel,date);
    onStatus('簽名已儲存，正在產生 '+customer+' '+period.startDate+'～'+date+' 對帳單…','working');
    const [master,pricing,effective,custom,template]=await context();
    if(!template.items?.length)throw new Error('缺少財務品項排序設定');
    const documents=await readPeriod(period.startDate,period.endDate);
    const rawLogisticsData=rowsForPeriod(documents,customer,period.startDate,period.endDate);
    const sheetPrices={};
    master.prices.slice(1).forEach(row=>{
     const h=String(row[0]).trim(),dept=String(row[1]||'').trim(),item=String(row[2]).trim();
     sheetPrices[(dept&&dept!==h?h+' '+dept:h)+'_'+item]=Number(row[3])||0;
    });
    const options={rawLogisticsData,sheetPrices,sheetClients:{},customPrices:custom.prices||{},
     logisticsMasterItems:template.items,effectivePriceRules:effective.rules||[],
     pricingRules:{holidays:pricing.holidays||[],rebates:pricing.rebates||[],managementFees:pricing.managementFees||[]}};
    options.sheetClients=createInvoiceEngine(options).parseFinanceClientRows(master.clients);
    const snapshot=createInvoiceEngine(options).build(customer,period.startDate,period.endDate);
    const result=await publishAutomaticOnce(db,fns,snapshot,{receiptIds:closingDocs.filter(x=>customerOf(x.data)===customer).map(x=>x.id)});
    if(result.action==='created')created++;else existing++;
   }
   remember(hotel,date,true);
  }
  if(created)onStatus('對帳單已產生 '+created+' 份，已放入送件中心。','success');
  else if(existing)onStatus('本期對帳單已在送件中心，沒有重複產生。','success');
  return {created,existing};
 }
 return {run(hotel,date){
  const work=chain.catch(()=>{}).then(()=>execute(hotel,date));
  chain=work.catch(()=>{});
  return work;
 }};
}
